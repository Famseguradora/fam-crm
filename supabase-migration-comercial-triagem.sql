create table if not exists public.caso_itens (
  id           uuid primary key default gen_random_uuid(),
  caso_id      uuid not null references public.casos(id) on delete cascade,
  item         text not null references public.caso_item_catalogo(id),
  situacao     text not null default 'faltando'
               check (situacao in ('ok','faltando','duvida','a_caminho','dispensado')),
  por          text not null default 'robo' check (por in ('robo','humano')),
  detalhe      text,
  alerta       text,
  arquivos     text[] not null default '{}',
  anos         integer[] not null default '{}',
  obs          text,
  decidido_em  timestamptz,
  decidido_por text,
  unique (caso_id, item)
);

comment on table public.caso_itens is
  'Uma linha por exigencia do catalogo, por caso. Item marcado por humano (por=humano) NUNCA e sobrescrito pelo robo: ele so cai sozinho quando o documento aparece de verdade.';

-- ── 4. RLS ──────────────────────────────────────────────────────────────────
-- Leitura: todo mundo autenticado (a equipe acompanha o trabalho acontecer).
-- Escrita: quem ja tem permissao de escrita no CRM (`fam_pode_escrever()`),
-- a mesma trava de `anexos`. Nunca `USING (true)` para `public`: `public`
-- inclui `anon`, e a chave publica do bundle passaria.
alter table public.casos             enable row level security;
alter table public.caso_documentos   enable row level security;
alter table public.caso_itens        enable row level security;
alter table public.caso_item_catalogo enable row level security;

drop policy if exists casos_leitura on public.casos;
create policy casos_leitura on public.casos
  for select to authenticated using (true);
drop policy if exists casos_escrita on public.casos;
create policy casos_escrita on public.casos
  for all to authenticated using (fam_pode_escrever()) with check (fam_pode_escrever());

drop policy if exists caso_documentos_leitura on public.caso_documentos;
create policy caso_documentos_leitura on public.caso_documentos
  for select to authenticated using (true);
drop policy if exists caso_documentos_escrita on public.caso_documentos;
create policy caso_documentos_escrita on public.caso_documentos
  for all to authenticated using (fam_pode_escrever()) with check (fam_pode_escrever());

drop policy if exists caso_itens_leitura on public.caso_itens;
create policy caso_itens_leitura on public.caso_itens
  for select to authenticated using (true);
drop policy if exists caso_itens_escrita on public.caso_itens;
create policy caso_itens_escrita on public.caso_itens
  for all to authenticated using (fam_pode_escrever()) with check (fam_pode_escrever());

drop policy if exists caso_item_catalogo_leitura on public.caso_item_catalogo;
create policy caso_item_catalogo_leitura on public.caso_item_catalogo
  for select to authenticated using (true);
drop policy if exists caso_item_catalogo_escrita on public.caso_item_catalogo;
create policy caso_item_catalogo_escrita on public.caso_item_catalogo
  for all to authenticated using (fam_gerencia_usuarios()) with check (fam_gerencia_usuarios());

-- ── 5. atualizado_em ────────────────────────────────────────────────────────
create or replace function public.casos_toca_atualizado_em()
returns trigger language plpgsql security invoker set search_path = public as $$
begin
  new.atualizado_em := now();
  return new;
end $$;

drop trigger if exists casos_atualizado_em on public.casos;
create trigger casos_atualizado_em before update on public.casos
  for each row execute function public.casos_toca_atualizado_em();

-- ── 6. `anexos` passa a aceitar o caso ──────────────────────────────────────
-- O arquivo continua num lugar so no CRM. Assim, quando a triagem conclui e o
-- tomador nasce, o documento que veio no e-mail ja esta no acervo de anexos e
-- pode seguir para a ficha do tomador em vez de virar uma segunda pilha.
alter table public.anexos drop constraint if exists anexos_entidade_tipo_check;
alter table public.anexos add constraint anexos_entidade_tipo_check
  check (entidade_tipo = any (array['tomador'::text,'operacao'::text,'corretora'::text,'caso'::text]));

-- ── 7. Teto de arquivo ──────────────────────────────────────────────────────
-- O bucket estava em 5 MB, e pacote de documentos de tomador real passa disso
-- (ha PDF de 12 MB no acervo). Sem isto, a triagem falha no primeiro caso.
update storage.buckets set file_size_limit = 52428800 where id = 'fam-anexos';
